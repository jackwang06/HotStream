def is_political(text: str) -> bool:
    """文本是否命中政治敏感词库（子串匹配）。"""
    if not text or _POLITICAL_RE is None:
        return False
    return _POLITICAL_RE.search(text) is not None


def _topic_text(topic: dict[str, Any]) -> str:
    return " ".join(str(topic.get(key) or "") for key in ("title", "desc", "label", "reason"))


def filter_political_topics(topics: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """剔除命中政治敏感词的热点；非 dict 项原样跳过。"""
    return [t for t in topics if not (isinstance(t, dict) and is_political(_topic_text(t)))]
